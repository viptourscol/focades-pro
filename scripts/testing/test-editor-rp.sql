-- Datos sinteticos y operaciones sobre copias. Nada persiste.
BEGIN;
DO $$
DECLARE
  v_edu UUID; v_pre UUID; v_conv UUID; v_otra UUID; v_ter UUID; v_rp UUID; v_legacy UUID; v_r JSONB; v_f JSONB; v_legacy_fila JSONB;
  v_filas JSONB; v_id UUID; v_persona UUID; v_ins UUID; v_benef BIGINT; v_ts TIMESTAMPTZ; v_error BOOLEAN; v_fuentes TEXT; v_busqueda JSONB;
  v_terceros JSONB := '[{"cc_nit":"000123","primer_nombre":"Ana","primer_apellido":"Perez","segundo_apellido":"Gomez","tipo_identificacion":"13","email":"prueba@example.test","telefono":"3001234567","direccion":"Direccion","banco":"Banco prueba","tipo_cuenta":"AHORROS","numero_cuenta":"000987","nombres_confirmados":true}]';
BEGIN
  v_terceros:=jsonb_set(jsonb_set(jsonb_set(v_terceros,'{0,primer_nombre}',to_jsonb(repeat('A',120))),
    '{0,primer_apellido}',to_jsonb(repeat('B',120))),'{0,segundo_apellido}',to_jsonb(repeat('C',120)));
  SELECT id INTO STRICT v_edu FROM auth.users WHERE raw_user_meta_data->'roles' @> '["admin_educacion"]'::JSONB ORDER BY created_at LIMIT 1;
  SELECT id INTO STRICT v_pre FROM auth.users WHERE raw_user_meta_data->'roles' @> '["admin_presupuesto"]'::JSONB AND NOT raw_user_meta_data->'roles' @> '["admin_educacion"]'::JSONB ORDER BY created_at LIMIT 1;
  INSERT INTO public.convocatorias(anio,nombre,is_activa) VALUES(2099,'RP SINTETICO ROLLBACK',FALSE) RETURNING id INTO v_conv;
  INSERT INTO public.convocatorias(anio,nombre,is_activa) VALUES(2099,'OTRA RP ROLLBACK',FALSE) RETURNING id INTO v_otra;
  INSERT INTO public.personas(email,nombre_completo,n_documento) VALUES('rp-sintetico@example.test','Persona RPZZPRUEBA','991234567890001') RETURNING id INTO v_persona;
  INSERT INTO public.inscripciones(radicado,convocatoria_id,nombre_completo,n_documento,modalidad) VALUES('RPZZPRUEBA',v_otra,'Inscripcion RPZZPRUEBA','991234567890002','SUEÑOS') RETURNING id INTO v_ins;
  INSERT INTO public.portal_beneficiarios(nombre_completo,n_documento,modalidad_beca) VALUES('Beneficiario RPZZPRUEBA','991234567890003','MÉRITO') RETURNING id INTO v_benef;
  SELECT md5(COALESCE(jsonb_agg(to_jsonb(p) ORDER BY id)::TEXT,'')) INTO v_fuentes FROM public.personas p;
  PERFORM set_config('request.jwt.claim.sub',v_edu::TEXT,TRUE);
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',v_edu,'role','authenticated')::TEXT,TRUE);
  SET LOCAL ROLE authenticated;
  v_busqueda:=public.buscar_personas_rp('RPZZPRUEBA');
  IF jsonb_array_length(v_busqueda)<>3 THEN RAISE EXCEPTION 'Busqueda global no encontro las tres fuentes sinteticas'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.buscar_personas_rp('ab'); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Acepto busqueda vacia/corta'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.fn_crear_documento_cargue(v_conv,'rp',0); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Creo RP sin TERCEROS aprobados'; END IF;
  v_ter:=public.fn_crear_documento_cargue(v_conv,'terceros',0);
  v_r:=public.guardar_terceros_cargue(v_ter,v_terceros,(SELECT editado_en FROM public.portal_documentos_cargue WHERE id=v_ter));
  v_id:=(v_r->'filas'->0->>'id')::UUID;
  PERFORM public.transicionar_documento_presupuesto(v_ter,'enviar','Revision');
  RESET ROLE; PERFORM set_config('request.jwt.claim.sub',v_pre::TEXT,TRUE); SET LOCAL ROLE authenticated;
  PERFORM public.transicionar_documento_presupuesto(v_ter,'aprobar','Completo');
  RESET ROLE; PERFORM set_config('request.jwt.claim.sub',v_edu::TEXT,TRUE); SET LOCAL ROLE authenticated;
  v_legacy:=public.fn_crear_documento_cargue(v_conv,'rp',0);
  RESET ROLE;
  PERFORM set_config('app.guardando_rp',v_legacy::TEXT,TRUE);
  INSERT INTO public.portal_valores_cargue(documento_id,identificacion,nombre_beneficiario,valor_bruto,valor_neto,numero_rp)
    VALUES(v_legacy,'000123','Referencia anterior',12.50,12.50,'0008');
  PERFORM set_config('app.guardando_rp','',TRUE);
  SET LOCAL ROLE authenticated;
  v_r:=public.leer_rp_cargue(v_legacy);
  v_legacy_fila:=v_r->'filas'->0;
  v_r:=public.guardar_rp_cargue(v_legacy,v_ter,jsonb_build_array(v_legacy_fila||jsonb_build_object('origen','tercero:'||v_id::TEXT)),(v_r->>'editado_en')::TIMESTAMPTZ);
  IF v_r->'filas'->0->>'valor'<>'12.50' OR v_r->'filas'->0->>'no_rp'<>'0008' THEN RAISE EXCEPTION 'Vincular origen perdio datos heredados'; END IF;
  v_rp:=public.fn_crear_documento_cargue(v_conv,'rp',0);
  IF jsonb_array_length(public.personas_terceros_rp(v_ter))<>1 THEN RAISE EXCEPTION 'No leyo personas de origen'; END IF;
  v_r:=public.leer_rp_cargue(v_rp);
  v_ts:=(v_r->>'editado_en')::TIMESTAMPTZ;
  IF v_r->'filas'<>'[]'::JSONB THEN RAISE EXCEPTION 'RP nuevo tiene filas inesperadas'; END IF;
  v_f:=jsonb_build_object('id',NULL,'origen','tercero:'||v_id::TEXT,'nombre','Ana Perez Gomez','modalidad','',
    'no_rp','','subconsecutivo','','descripcion','','fecha','','no_cdp','','subconsecutivo_cdp','',
    'tercero_presupuestal','000123','origen_legal_apropiacion','5','proyecto','841','entidad','9901',
    'rubro_presupuestal','2.3.2.02.02.009','fuente_financiacion','','valor','','liquidacion','','contrato','',
    'firma_mecanica','NO','valor_confirmado',FALSE,'tercero_confirmado',FALSE);
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"no_rp":"10"}'),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=SQLERRM LIKE '%Presupuesto%'; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Educacion completo No RP'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"tercero_presupuestal":"999"}'),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Falsifico identificacion de origen'; END IF;
  v_r:=public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f),v_ts);
  IF length(v_r->'filas'->0->>'nombre')<>362 THEN RAISE EXCEPTION 'Trunco el nombre completo del tercero'; END IF;
  v_ts:=(v_r->>'editado_en')::TIMESTAMPTZ; v_f:=v_r->'filas'->0;
  -- La busqueda puede agregar personas de otras convocatorias, pero no inventar fuentes.
  v_r:=public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f,
    v_f||jsonb_build_object('id',NULL,'origen','inscripcion:'||v_ins::TEXT,'tercero_presupuestal','991234567890002')),v_ts);
  IF jsonb_array_length(v_r->'filas')<>2 THEN RAISE EXCEPTION 'No agrego persona de otra convocatoria'; END IF;
  v_ts:=(v_r->>'editado_en')::TIMESTAMPTZ;
  v_r:=public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f),v_ts);
  v_ts:=(v_r->>'editado_en')::TIMESTAMPTZ;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f,v_f),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Acepto duplicados'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.transicionar_documento_presupuesto(v_rp,'enviar','Falta importe'); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Envio sin valor'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"valor":"1e5","liquidacion":"1e5"}'),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Admitio notacion cientifica'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"valor":"10000000000000.00","liquidacion":"10000000000000.00"}'),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Admitio 14 enteros'; END IF;
  v_r:=public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"valor":"9999999999999.99","liquidacion":"9999999999999.99","valor_confirmado":true}'),v_ts);
  v_f:=v_r->'filas'->0;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,v_r->'filas',v_ts); EXCEPTION WHEN raise_exception THEN v_error:=SQLERRM LIKE '%cambio%'; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Sobrescribio revision desactualizada'; END IF;
  PERFORM public.transicionar_documento_presupuesto(v_rp,'enviar','Datos de Educacion listos');
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f),(SELECT editado_en FROM public.portal_documentos_cargue WHERE id=v_rp)); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Educacion edito en revision'; END IF;
  RESET ROLE; PERFORM set_config('request.jwt.claim.sub',v_pre::TEXT,TRUE); SET LOCAL ROLE authenticated;
  v_error:=FALSE;
  BEGIN PERFORM public.buscar_personas_rp('RPZZPRUEBA'); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Presupuesto pudo buscar/agregar personas'; END IF;
  v_ts:=(public.leer_rp_cargue(v_rp)->>'editado_en')::TIMESTAMPTZ;
  v_error:=FALSE;
  BEGIN PERFORM public.transicionar_documento_presupuesto(v_rp,'aprobar','Faltan datos'); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Aprobo incompleto'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.obtener_rp_exportacion(v_rp); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Exporto incompleto'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"valor":"1","liquidacion":"1"}'),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Presupuesto cambio importes'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,'[]',v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Presupuesto elimino persona'; END IF;
  v_f:=v_f||'{"no_rp":"000001","subconsecutivo":"0001","descripcion":"Registro de prueba","fecha":"29022025","no_cdp":"000002","subconsecutivo_cdp":"0001","fuente_financiacion":"0004","contrato":"","tercero_confirmado":true}';
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f),v_ts); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Guardo fecha inexistente'; END IF;
  v_r:=public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"fecha":"13112026"}'),v_ts);
  v_f:=v_r->'filas'->0;
  v_filas:=public.obtener_rp_exportacion(v_rp);
  IF v_filas->0->>'valor'<>'9999999999999.99' OR v_filas->0->>'no_rp'<>'000001' THEN RAISE EXCEPTION 'Perdio precision o ceros'; END IF;
  IF (SELECT estado FROM public.portal_documentos_cargue WHERE id=v_rp)<>'enviado_para_revision' THEN RAISE EXCEPTION 'Exportar aprobo'; END IF;
  PERFORM public.transicionar_documento_presupuesto(v_rp,'rechazar','Verificar importe con Educacion');
  RESET ROLE; PERFORM set_config('request.jwt.claim.sub',v_edu::TEXT,TRUE); SET LOCAL ROLE authenticated;
  PERFORM public.transicionar_documento_presupuesto(v_rp,'reabrir','Revision de Educacion');
  v_r:=public.leer_rp_cargue(v_rp);
  IF v_r->'filas'->0->>'no_rp'<>'000001' OR v_r->'filas'->0->>'valor'<>'9999999999999.99' THEN RAISE EXCEPTION 'Reabrir perdio datos'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f||'{"no_cdp":"123"}'),(v_r->>'editado_en')::TIMESTAMPTZ);
    EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Educacion modifico campos de Presupuesto al reabrir'; END IF;
  PERFORM public.transicionar_documento_presupuesto(v_rp,'enviar','Importe confirmado');
  RESET ROLE; PERFORM set_config('request.jwt.claim.sub',v_pre::TEXT,TRUE); SET LOCAL ROLE authenticated;
  PERFORM public.transicionar_documento_presupuesto(v_rp,'aprobar','Verificado');
  IF (SELECT aprobado_por FROM public.portal_documentos_cargue WHERE id=v_rp) IS DISTINCT FROM v_pre THEN RAISE EXCEPTION 'Falta aprobador'; END IF;
  v_error:=FALSE;
  BEGIN PERFORM public.guardar_rp_cargue(v_rp,v_ter,jsonb_build_array(v_f),(SELECT editado_en FROM public.portal_documentos_cargue WHERE id=v_rp)); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Edito aprobado'; END IF;
  RESET ROLE;
  PERFORM set_config('request.jwt.claim.sub',v_edu::TEXT,TRUE);
  v_error:=FALSE;
  BEGIN UPDATE public.portal_valores_cargue SET valor_bruto=1 WHERE documento_id=v_rp; EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Mutacion directa evadio bloqueo'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.portal_transiciones_documento WHERE documento_id=v_rp AND datos_cambio ? 'antes' AND datos_cambio ? 'despues') THEN RAISE EXCEPTION 'Falta auditoria de cambios'; END IF;
  IF v_fuentes IS DISTINCT FROM (SELECT md5(COALESCE(jsonb_agg(to_jsonb(p) ORDER BY id)::TEXT,'')) FROM public.personas p) THEN RAISE EXCEPTION 'Modifico perfiles'; END IF;
  IF has_function_privilege('anon','public.guardar_rp_cargue(uuid,uuid,jsonb,timestamptz)','EXECUTE') THEN RAISE EXCEPTION 'Anon autorizado'; END IF;
  PERFORM set_config('request.jwt.claim.sub','',TRUE);
  PERFORM set_config('request.jwt.claims','{"role":"authenticated"}',TRUE);
  SET LOCAL ROLE authenticated;
  v_error:=FALSE;
  BEGIN PERFORM public.obtener_rp_exportacion(v_rp); EXCEPTION WHEN raise_exception THEN v_error:=TRUE; END;
  IF NOT v_error THEN RAISE EXCEPTION 'Sin rol pudo exportar'; END IF;
  RESET ROLE;
END;
$$;
